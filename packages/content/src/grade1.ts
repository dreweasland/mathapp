import type { QuestionType, SkillDef } from '@mathapp/engine';

const MASTERY = { threshold: 80, minAttempts: 15 };
const FACT_MS = 3000;

/** Shared by every grade. Prerequisites are full ids, so a skill can reach across grades. */
export function defineSkill(
  grade: SkillDef['grade'],
  order: number,
  slug: string,
  standard: string,
  name: string,
  kidName: string,
  badgeName: string,
  prerequisites: string[],
  questionTypes: QuestionType[],
  fastMs: number,
  factBased = false,
): SkillDef {
  const id = `${grade}.${slug}`;
  return {
    id,
    grade,
    standard,
    name,
    kidName,
    speechKey: `skill.${id}`,
    badgeName,
    prerequisites,
    questionTypes,
    fastMs,
    factBased,
    mastery: MASTERY,
    order,
  };
}

const skill = (
  order: number,
  slug: string,
  standard: string,
  name: string,
  kidName: string,
  badgeName: string,
  prerequisites: string[],
  questionTypes: QuestionType[],
  fastMs: number,
  factBased = false,
): SkillDef =>
  defineSkill(
    1,
    order,
    slug,
    standard,
    name,
    kidName,
    badgeName,
    prerequisites.map((p) => `1.${p}`),
    questionTypes,
    fastMs,
    factBased,
  );

